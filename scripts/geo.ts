// Regenerates the two static datasets behind the outage map. Run by hand, rarely:
//
//   curl -sL $(npm view world-atlas@2.0.2 dist.tarball) | tar xz   # package/land-110m.json
//   curl -sLO https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv
//   bun scripts/geo.ts package/land-110m.json airports.csv
//
// Writes src/lib/geo/land.ts (the dotted world, one SVG path) and
// src/lib/geo/airports.ts (IATA code → lat/lon for airports with scheduled flights).
// Both sources are public domain (Natural Earth via world-atlas, OurAirports).
import { readFileSync, writeFileSync } from "node:fs";
import { LAT_TOP, LAT_BOTTOM, STEP } from "../src/lib/geo/projection";

const [landPath, airportsPath] = process.argv.slice(2);
if (!landPath || !airportsPath) {
  console.error("usage: bun scripts/geo.ts <land-110m.json> <airports.csv>");
  process.exit(1);
}

type Ring = [number, number][];

// TopoJSON → polygons (rings of lon/lat). Just enough of the format for world-atlas.
function landPolygons(topo: {
  transform: { scale: [number, number]; translate: [number, number] };
  arcs: [number, number][][];
  objects: { land: { geometries: { type: string; arcs: number[][] | number[][][] }[] } };
}): Ring[][] {
  const { scale, translate } = topo.transform;
  const arcs = topo.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * scale[0] + translate[0], y * scale[1] + translate[1]] as [number, number];
    });
  });
  const ring = (ids: number[]): Ring =>
    ids.flatMap((id, k) => {
      const a = id < 0 ? [...arcs[~id]].reverse() : arcs[id];
      return k ? a.slice(1) : a;
    });
  const out: Ring[][] = [];
  for (const g of topo.objects.land.geometries) {
    const polys = g.type === "Polygon" ? [g.arcs as number[][]] : (g.arcs as number[][][]);
    for (const p of polys) out.push(p.map(ring));
  }
  return out;
}

function inRing(x: number, y: number, r: Ring): boolean {
  let inside = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i];
    const [xj, yj] = r[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const onLand = (polys: Ring[][], lon: number, lat: number) =>
  polys.some(([outer, ...holes]) => [lon, lon + 360, lon - 360].some((x) => inRing(x, lat, outer) && !holes.some((h) => inRing(x, lat, h))));

// Rings that cross the antimeridian (Chukotka, Fiji) jump from 180 to -180; unwrap
// them so each edge is short, and test points at lon ± 360 as well.
const unwrap = (r: Ring): Ring => {
  let shift = 0;
  return r.map(([x, y], k) => {
    if (k) {
      const prev = r[k - 1][0];
      if (x - prev > 180) shift -= 360;
      else if (prev - x > 180) shift += 360;
    }
    return [x + shift, y];
  });
};

const polys = landPolygons(JSON.parse(readFileSync(landPath, "utf8"))).map((p) => p.map(unwrap));

// A grid cell is land if its centre or any of four inner points is: small islands
// (Singapore, Hawaii) still get a dot.
const cellLand = (lon: number, lat: number) =>
  [[0, 0], [-0.3, -0.3], [0.3, -0.3], [-0.3, 0.3], [0.3, 0.3]].some(([dx, dy]) => onLand(polys, lon + dx * STEP, lat + dy * STEP));

// Runs of land dots along each row, as "M x y h len". The path is drawn with a
// round-capped dash of length 0 every STEP, so each run becomes a row of dots.
const runs: string[] = [];
let dots = 0;
for (let lat = LAT_TOP - STEP / 2; lat > LAT_BOTTOM; lat -= STEP) {
  let start: number | null = null;
  const flush = (end: number) => {
    if (start === null) return;
    const y = LAT_TOP - lat;
    runs.push(`M${start + 180} ${+y.toFixed(2)}h${end - start}`);
    start = null;
  };
  let last = 0;
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    if (cellLand(lon, lat)) {
      dots++;
      if (start === null) start = lon;
      last = lon;
    } else flush(last);
  }
  flush(last);
}

writeFileSync(
  "src/lib/geo/land.ts",
  `// Generated by scripts/geo.ts from Natural Earth (world-atlas land-110m). ${dots} dots.\n` +
    `export const LAND_PATH = ${JSON.stringify(runs.join(""))};\n`,
);

// IATA → [lat, lon], one decimal. Medium and large airports with scheduled flights:
// covers every point of presence a CDN names by airport code.
const rows = readFileSync(airportsPath, "utf8").split("\n");
const head = parseCsv(rows[0]);
const col = (n: string) => head.indexOf(n);
const seen = new Map<string, string>();
for (const line of rows.slice(1)) {
  if (!line) continue;
  const r = parseCsv(line);
  const iata = r[col("iata_code")];
  if (!/^[A-Z]{3}$/.test(iata) || r[col("scheduled_service")] !== "yes") continue;
  const type = r[col("type")];
  if (type !== "large_airport" && type !== "medium_airport") continue;
  // A code shared by a large and a medium airport: the large one wins.
  if (seen.has(iata) && type !== "large_airport") continue;
  seen.set(iata, `${iata}${+(+r[col("latitude_deg")]).toFixed(1)},${+(+r[col("longitude_deg")]).toFixed(1)}`);
}
const packed = [...seen.keys()].sort().map((k) => seen.get(k)).join(";");
writeFileSync(
  "src/lib/geo/airports.ts",
  `// Generated by scripts/geo.ts from OurAirports (public domain). ${seen.size} airports.\n` +
    `// "IATAlat,lon;..." to keep the module small; decoded once by places.ts.\n` +
    `export const AIRPORTS = ${JSON.stringify(packed)};\n`,
);
console.log(`${dots} land dots in ${runs.length} runs, ${seen.size} airports`);

function parseCsv(line: string): string[] {
  const out: string[] = [];
  let cur = "";
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === '"' && line[i + 1] === '"') (cur += '"'), i++;
      else if (c === '"') q = false;
      else cur += c;
    } else if (c === '"') q = true;
    else if (c === ",") out.push(cur), (cur = "");
    else cur += c;
  }
  out.push(cur);
  return out;
}
